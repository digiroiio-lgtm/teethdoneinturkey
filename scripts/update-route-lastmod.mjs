#!/usr/bin/env node
// Regenerates seo/route-lastmod.json — the per-URL freshness manifest the
// sitemap reads.
//
// Why a manifest and not `new Date()` or `git log`:
//   * `new Date()` bumps every URL on every deploy. Google learns that our
//     lastmod carries no information and starts ignoring it.
//   * `git log` is unavailable where it matters — Vercel and CI check out
//     shallow/without history, so dates would silently collapse to one value.
//
// So freshness is derived from content: each route gets a fingerprint of its own
// source files (see scripts/lib/site-routes.mjs). A route keeps its stored
// lastmod for as long as its fingerprint is unchanged, and only moves to "now"
// when the page itself is actually edited. New pages enter the manifest — and
// therefore the sitemap — automatically.
//
// Usage:
//   node scripts/update-route-lastmod.mjs            # rewrite the manifest
//   node scripts/update-route-lastmod.mjs --check     # fail if it is stale (CI)
//   node scripts/update-route-lastmod.mjs --now=<ISO> # pin the timestamp

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { discoverRoutes } from './lib/site-routes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP_DIR = path.join(ROOT, 'src', 'app');
const MANIFEST = path.join(ROOT, 'seo', 'route-lastmod.json');

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const nowArg = args.find((arg) => arg.startsWith('--now='))?.slice('--now='.length);

const now = nowArg ? new Date(nowArg) : new Date();
if (Number.isNaN(now.getTime())) {
  console.error(`update-route-lastmod: --now is not a valid date: ${nowArg}`);
  process.exit(1);
}
// Second-level precision is plenty for a sitemap and keeps diffs readable.
const timestamp = `${now.toISOString().slice(0, 19)}Z`;

const previous = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : { routes: {} };
const previousRoutes = previous.routes ?? {};

const routes = {};
const added = [];
const changed = [];

for (const { route, hash } of discoverRoutes(APP_DIR)) {
  const before = previousRoutes[route];
  if (!before) {
    added.push(route);
    routes[route] = { lastmod: timestamp, hash };
  } else if (before.hash !== hash) {
    changed.push(route);
    routes[route] = { lastmod: timestamp, hash };
  } else {
    routes[route] = { lastmod: before.lastmod, hash };
  }
}

const removed = Object.keys(previousRoutes).filter((route) => !(route in routes));

const next = {
  $comment:
    'Generated by scripts/update-route-lastmod.mjs. Do not hand-edit: a route keeps its lastmod until its own source files change. Run `npm run seo:lastmod` after editing page content.',
  routes,
};

const serialised = `${JSON.stringify(next, null, 2)}\n`;
const current = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, 'utf8') : '';

if (checkOnly) {
  if (serialised === current) {
    console.log(`update-route-lastmod: manifest is current (${Object.keys(routes).length} routes).`);
    process.exit(0);
  }
  console.error('update-route-lastmod: seo/route-lastmod.json is out of date.');
  for (const route of added) console.error(`  + ${route} (new page, missing from the sitemap)`);
  for (const route of changed) console.error(`  ~ ${route} (content changed, lastmod is stale)`);
  for (const route of removed) console.error(`  - ${route} (page no longer exists)`);
  console.error('Run `npm run seo:lastmod` and commit seo/route-lastmod.json.');
  process.exit(1);
}

fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
fs.writeFileSync(MANIFEST, serialised);

const summary = [
  `${Object.keys(routes).length} routes`,
  added.length ? `${added.length} added` : null,
  changed.length ? `${changed.length} updated` : null,
  removed.length ? `${removed.length} removed` : null,
]
  .filter(Boolean)
  .join(', ');
console.log(`update-route-lastmod: ${summary}.`);
for (const route of added) console.log(`  + ${route}`);
for (const route of changed) console.log(`  ~ ${route}`);
for (const route of removed) console.log(`  - ${route}`);
